"""
gen_fyp_table3_scope.py
FYP Table 3 — Scope/claim matrix with explicit boundary column.

Data source: figures/data/fyp_claim_scope.json
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DATA_PATH = HERE / "data" / "fyp_claim_scope.json"
OUT_PATH = HERE / "TABLE3_fyp_claim_scope.tex"


def esc(text):
    return (
        text.replace("\\", "\\textbackslash{}")
            .replace("_", "\\_")
            .replace("%", "\\%")
            .replace("&", "\\&")
    )


with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)

lines = []
lines.append(r"% TABLE3_fyp_claim_scope.tex — generated by gen_fyp_table3_scope.py")
lines.append(r"\begin{table*}[t]")
lines.append(r"\centering")
lines.append(
    r"\caption{Scope and boundary matrix. Every claim is paired with its key evidence, "
    r"the scope under which it holds, and the explicit boundary or limitation. "
    r"Claims marked with a failure boundary are part of the reported result.}"
)
lines.append(r"\label{tab:fyp_claim_scope}")
lines.append(r"\setlength{\tabcolsep}{4pt}")
lines.append(r"\begin{tabular}{p{3.2cm}p{3.2cm}p{2.8cm}p{3.6cm}}")
lines.append(r"\toprule")
lines.append(r"\textbf{Claim} & \textbf{Key evidence} & \textbf{Scope} & \textbf{Explicit boundary} \\")
lines.append(r"\midrule")

for row in data["rows"]:
    lines.append(
        f'{esc(row["claim"])} & '
        f'{esc(row["evidence"])} & '
        f'{esc(row["scope"])} & '
        f'{esc(row["boundary"])} \\\\'
    )

lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table*}")

OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Saved: {OUT_PATH}")
