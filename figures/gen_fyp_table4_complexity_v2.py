"""
gen_fyp_table4_complexity_v2.py
FYP Table 4 — Frozen corrector complexity and deployment overhead (improved).

Includes: runtime delta, memory, extra test-time dependencies.

Data source: figures/data/model_complexity.json
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DATA_PATH = HERE / "data" / "model_complexity.json"
OUT_PATH = HERE / "TABLE4_fyp_complexity.tex"


def fmt_val(v):
    if isinstance(v, str) and "PLACEHOLDER" in v:
        return r"\textit{---}"
    return str(v)


with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)


rows = [
    ("Model type", "2-layer MLP (classification)"),
    ("Input dimension", f"{data['input_dim']}" + r" (observable receiver features)"),
    ("Hidden layers / size", f"{data['hidden_layers']} layers, " + fmt_val(data["hidden_size"]) + " units each"),
    ("Activation", fmt_val(data["activation"])),
    ("Output", r"1 logit (flip/keep binary decision per bit)"),
    ("Total parameters", fmt_val(data["total_parameters"])),
    ("Training data", r"Single nominal cache; offline; no test-time retraining"),
    ("Deployment", r"Frozen; vectorised 1-pass over frame; no back-propagation"),
    ("Extra test-time inputs", data["test_time_extra_inputs"]),
    ("Runtime overhead vs backbone", fmt_val(data["runtime_delta_vs_backbone"])),
    ("Memory overhead", fmt_val(data["memory_delta"])),
]

lines = []
lines.append(r"% TABLE4_fyp_complexity.tex — generated by gen_fyp_table4_complexity_v2.py")
lines.append(r"\begin{table}[t]")
lines.append(r"\centering")
lines.append(
    r"\caption{Frozen corrector complexity and deployment overhead. "
    r"All 12 input features are already available from the backbone receiver trajectory, "
    r"so no extra inference stage is required at test time. "
    r"Fields marked `---' require values from the verified implementation.}"
)
lines.append(r"\label{tab:fyp_complexity}")
lines.append(r"\setlength{\tabcolsep}{5pt}")
lines.append(r"\begin{tabular}{ll}")
lines.append(r"\toprule")
lines.append(r"\textbf{Property} & \textbf{Value} \\")
lines.append(r"\midrule")

for prop, val in rows:
    prop_esc = prop.replace("_", r"\_")
    val_esc = val.replace("_", r"\_").replace("&", r"\&") if r"\textit" not in val else val
    lines.append(f"{prop_esc} & {val_esc} \\\\")

lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table}")

OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Saved: {OUT_PATH}")
