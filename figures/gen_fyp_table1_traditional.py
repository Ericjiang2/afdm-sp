"""
gen_fyp_table1_traditional.py
FYP Table 1 — Traditional receiver family comparison.

Data source: figures/data/traditional_receiver_summary.json
IMPORTANT: BER values are PLACEHOLDER — fill from experiment logs.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DATA_PATH = HERE / "data" / "traditional_receiver_summary.json"
OUT_PATH = HERE / "TABLE1_traditional.tex"

with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)


def fmt_ber(val):
    if val == "PLACEHOLDER":
        return r"\textit{---}"
    return f"{float(val):.4e}"


lines = []
lines.append(r"% TABLE1_traditional.tex — generated by gen_fyp_table1_traditional.py")
lines.append(r"\begin{table}[t]")
lines.append(r"\centering")
lines.append(r"\caption{Traditional receiver family comparison at SNR\,=\,15\,dB under the Python-aligned evaluation protocol "
             r"(100 frames, seed\,=\,42). "
             r"TRADPARAM Fixed is the strongest clean traditional representative, outperforming JointOMP-MP. "
             r"CurrentJoint (learned backbone) is included for context.}")
lines.append(r"\label{tab:traditional_receivers}")
lines.append(r"\setlength{\tabcolsep}{5pt}")
lines.append(r"\begin{tabular}{lllll}")
lines.append(r"\toprule")
lines.append(r"\textbf{Method} & \textbf{Key Idea} & \textbf{Protocol} & \textbf{SNR (dB)} & \textbf{BER} \\")
lines.append(r"\midrule")

for m in data["methods"]:
    ber_str = fmt_ber(m["ber_at_snr"])
    label = m["label"].replace("_", r"\_")
    idea = m["key_idea"].replace("_", r"\_").replace("&", r"\&")
    # Truncate key idea for table width
    if len(idea) > 55:
        idea = idea[:52] + "..."
    proto = m["evaluation"].replace("_", r"\_")
    snr_ref = str(m.get("snr_db_reference", "---"))
    row = f"{label} & {idea} & {proto} & {snr_ref} & {ber_str} \\\\"
    lines.append(row)

lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table}")

tex = "\n".join(lines) + "\n"
OUT_PATH.write_text(tex, encoding="utf-8")
print(f"Saved: {OUT_PATH}")
print(tex)
