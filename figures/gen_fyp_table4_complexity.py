"""
gen_fyp_table4_complexity.py
FYP Table 4 — Frozen corrector complexity and overhead.

Data source: figures/data/model_complexity.json
IMPORTANT: hidden_size and total_parameters are PLACEHOLDER — fill from code.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DATA_PATH = HERE / "data" / "model_complexity.json"
OUT_PATH = HERE / "TABLE4_complexity.tex"

with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)


def fmt_val(v):
    if v == "PLACEHOLDER" or (isinstance(v, str) and "PLACEHOLDER" in v):
        return r"\textit{---}"
    return str(v)


rows = [
    ("Model type", "2-layer MLP (ReLU activations)"),
    ("Input dimension", str(data["input_dim"]) + r" (observable receiver trajectory features)"),
    ("Hidden layers", str(data["hidden_layers"])),
    ("Hidden size", fmt_val(data["hidden_size"])),
    ("Output dimension", str(data["output_dim"]) + r" (bit correction logit)"),
    ("Total parameters", fmt_val(data["total_parameters"])),
    ("Training mode", data["training_mode"]),
    ("Deployment mode", data["deployment_mode"]),
    ("Training cache size", fmt_val(data["training_cache_size"])),
]

lines = []
lines.append(r"% TABLE4_complexity.tex — generated by gen_fyp_table4_complexity.py")
lines.append(r"\begin{table}[t]")
lines.append(r"\centering")
lines.append(r"\caption{Frozen corrector complexity and overhead. Training is performed offline on a single dedicated nominal cache. "
             r"Deployment requires one frozen forward pass per bit, vectorised over the frame.}")
lines.append(r"\label{tab:complexity}")
lines.append(r"\setlength{\tabcolsep}{5pt}")
lines.append(r"\begin{tabular}{ll}")
lines.append(r"\toprule")
lines.append(r"\textbf{Property} & \textbf{Value} \\")
lines.append(r"\midrule")

for prop, val in rows:
    val_esc = val.replace("_", r"\_").replace("&", r"\&")
    prop_esc = prop.replace("_", r"\_")
    lines.append(f"{prop_esc} & {val_esc} \\\\")

lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table}")

tex = "\n".join(lines) + "\n"
OUT_PATH.write_text(tex, encoding="utf-8")
print(f"Saved: {OUT_PATH}")
print(tex)
