"""
gen_fyp_table2_method_comparison.py
FYP Table 2 — Method evolution with outcome after correction and reason status.

Data source: figures/data/fyp_method_comparison.json
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DATA_PATH = HERE / "data" / "fyp_method_comparison.json"
OUT_PATH = HERE / "TABLE2_fyp_method_comparison.tex"


def esc(text):
    return (
        text.replace("\\", "\\textbackslash{}")
            .replace("_", "\\_")
            .replace("%", "\\%")
            .replace("&", "\\&")
            .replace("~", "\\textasciitilde{}")
    )


with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)

# Status → formatting
def fmt_status(s):
    s_lo = s.lower()
    if "main contribution" in s_lo:
        return r"\textbf{Main contribution}"
    if "dropped" in s_lo:
        return r"\textit{Dropped}"
    if "viability" in s_lo:
        return r"\textit{Bridge}"
    return esc(s)

lines = []
lines.append(r"% TABLE2_fyp_method_comparison.tex — generated by gen_fyp_table2_method_comparison.py")
lines.append(r"\begin{table*}[t]")
lines.append(r"\centering")
lines.append(
    r"\caption{Method evolution under the corrected evaluation protocol. "
    r"The ``Outcome after correction'' column shows what changed once the evaluation bug was fixed. "
    r"The status column indicates the role each method plays in the final narrative.}"
)
lines.append(r"\label{tab:fyp_method_evolution}")
lines.append(r"\setlength{\tabcolsep}{4pt}")
lines.append(r"\begin{tabular}{p{2.4cm}p{2.0cm}p{2.4cm}p{3.6cm}p{3.0cm}}")
lines.append(r"\toprule")
lines.append(r"\textbf{Method} & \textbf{Family} & \textbf{Protocol} & "
             r"\textbf{Outcome after correction} & \textbf{Status} \\")
lines.append(r"\midrule")

for m in data["methods"]:
    row = (
        f'{esc(m["method"])} & '
        f'{esc(m["family"])} & '
        f'{esc(m["test_protocol"])} & '
        f'{esc(m["outcome_after_correction"])} & '
        f'{fmt_status(m["status"])} \\\\'
    )
    lines.append(row)

lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table*}")

OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Saved: {OUT_PATH}")
